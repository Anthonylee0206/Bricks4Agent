    private static void TestSearchHistoryTool()
    {
        Console.WriteLine("--- search_history returns hits with the following reply ---");
        using var f = new Fixture();
        var topic = f.Memory.GetOrCreateActiveTopic(f.UserId);
        f.Memory.AppendMessage(f.UserId, "user", "幫我查台鐵 台北到高雄", topic);
        f.Memory.AppendMessage(f.UserId, "assistant", "下一班是 10:30 自強號", topic);
        f.Memory.AppendMessage(f.UserId, "user", "今天天氣如何", topic);
        var tool = f.Services.GetServices<INyaToolPlugin>().OfType<HistorySearchToolPlugin>().Single();
        var ok = tool.ExecuteAsync(Ctx(f.UserId, "{\"query\":\"台鐵 高雄\"}"), CancellationToken.None).GetAwaiter().GetResult();
        AssertTrue("search-success", ok.Success);
        AssertTrue("search-hit", ok.LlmContent.Contains("台北到高雄"));
        AssertTrue("search-followed-by", ok.LlmContent.Contains("10:30 自強號"));
        AssertTrue("search-not-escaped", !ok.LlmContent.Contains("\\u"));
        var none = tool.ExecuteAsync(Ctx(f.UserId, "{\"query\":\"不存在的關鍵字QQ\"}"), CancellationToken.None).GetAwaiter().GetResult();
        AssertTrue("search-none-ok", none.Success && none.LlmContent.Contains("\"found\":0"));
        var missing = tool.ExecuteAsync(Ctx(f.UserId, "{}"), CancellationToken.None).GetAwaiter().GetResult();
        AssertTrue("search-missing-query-fails", !missing.Success);
        var exposed = f.Services.GetRequiredService<NyaToolRegistry>().BuildLlmTools(f.UserId, "line")
            .Any(t => t.Function.Name == "search_history");
        AssertTrue("search-exposed", exposed);
    }

    private static void TestUpsertStoresSourceAndExpiry()
    {
        Console.WriteLine("--- upsert_fact keeps the user's words and expiry ---");
        using var f = new Fixture();
        var tool = f.Services.GetServices<INyaToolPlugin>().OfType<FactToolPlugin>().Single();
        var res = tool.ExecuteAsync(new NyaToolContext
        {
            ToolName = "upsert_fact", UserId = f.UserId, ChannelType = "line",
            ArgumentsJson = "{\"category\":\"context\",\"key\":\"interview\",\"value\":\"明天面試\",\"source_text\":\"明天要面試有點緊張\",\"expires_in_days\":2}"
        }, CancellationToken.None).GetAwaiter().GetResult();
        AssertTrue("upsert-ok", res.Success);
        var fact = f.Memory.GetActiveFacts(f.UserId).Single(x => x.FactKey == "interview");
        AssertEqual("source-text", "明天要面試有點緊張", fact.SourceText);
        AssertTrue("expiry-set", fact.ExpiresAt is { } e && e > DateTime.UtcNow.AddDays(1) && e < DateTime.UtcNow.AddDays(3));
        var del = tool.ExecuteAsync(new NyaToolContext
        {
            ToolName = "delete_fact", UserId = f.UserId, ChannelType = "line", ArgumentsJson = "{\"key\":\"interview\"}"
        }, CancellationToken.None).GetAwaiter().GetResult();
        AssertTrue("delete-forgets", del.Success && f.Memory.GetForgotten(f.UserId).Any(x => x.FactKey == "interview"));
        var missing = tool.ExecuteAsync(new NyaToolContext
        {
            ToolName = "delete_fact", UserId = f.UserId, ChannelType = "line", ArgumentsJson = "{\"key\":\"interview\"}"
        }, CancellationToken.None).GetAwaiter().GetResult();
        AssertTrue("delete-missing-fails", !missing.Success && missing.LlmContent.Contains("note_not_found"));
    }

    private static void TestSummaryRollbackStaysInTopic()
    {
        Console.WriteLine("--- summary rollback only touches its own topic ---");
        using var f = new Fixture();
        var m = f.Memory;
        var topicA = m.CreateNewTopic(f.UserId, "A").TopicId;
        var a1 = m.CreateSummary(f.UserId, topicA, "A1", 1, 2, 2);
        m.CreateSummary(f.UserId, topicA, "A2", 3, 4, 2);
        var topicB = m.CreateNewTopic(f.UserId, "B").TopicId;
        var b1 = m.CreateSummary(f.UserId, topicB, "B1", 5, 6, 2);
        var restored = m.RollbackSummary(f.UserId, a1.SummaryId);
        AssertTrue("rollback-restored", restored?.SummaryId == a1.SummaryId);
        var active = m.GetSummaryHistory(f.UserId).Where(x => x.IsActive).ToList();
        AssertEqual("one-active-in-a", 1, active.Count(x => x.TopicId == topicA));
        AssertTrue("a-active-is-a1", active.Any(x => x.SummaryId == a1.SummaryId));
        AssertTrue("b-untouched", active.Any(x => x.SummaryId == b1.SummaryId));
    }

    private static void TestForgettingTurnAndSummaries()
    {
        Console.WriteLine("--- the forgetting turn itself and derived summaries are covered ---");
        using var f = new Fixture();
        var topic = f.Memory.GetOrCreateActiveTopic(f.UserId);
        f.Memory.AppendMessage(f.UserId, "user", "我住在台中北屯", topic);
        f.Memory.UpsertFact(f.UserId, "identity", "home", "台中北屯");
        f.Memory.CreateSummary(f.UserId, topic, "使用者住在台中北屯", 1, 1, 1);
        f.Memory.CreateSummary(f.UserId, topic, "使用者喜歡貓", 2, 2, 1);
        f.Memory.ForgetFact(f.UserId, "home");
        f.Memory.AppendMessage(f.UserId, "user", "把我住台中北屯這件事忘掉", topic);
        f.Memory.AppendMessage(f.UserId, "assistant", "好，台中北屯我忘掉了", topic);
        f.Memory.AppendMessage(f.UserId, "user", "之後再說台中北屯也可以", topic);
        var visible = f.Memory.GetRecentConversation(f.UserId, null).Select(m => m.Content).ToList();
        AssertTrue("forget-request-hidden", !visible.Contains("把我住台中北屯這件事忘掉"));
        AssertTrue("forget-reply-hidden", !visible.Contains("好，台中北屯我忘掉了"));
        AssertTrue("later-disclosure-visible", visible.Contains("之後再說台中北屯也可以"));
        var summaries = f.Memory.GetSummaryHistory(f.UserId).Select(x => x.SummaryText).ToList();
        AssertTrue("summary-with-forgotten-removed", !summaries.Any(t => t.Contains("台中北屯")));
        AssertTrue("unrelated-summary-kept", summaries.Contains("使用者喜歡貓"));
        AssertTrue("quoted-claim-ignored", ((IReadOnlyList<string>)typeof(NyaToolReplyPlanner).GetMethod("DetectCompletedActions", System.Reflection.BindingFlags.Static | System.Reflection.BindingFlags.NonPublic)!.Invoke(null, new object[] { "你可以跟我說「已經記住」來確認。" })!).Count == 0);
    }

    private static void TestUpgradeCompatibility()
    {
        Console.WriteLine("--- upgrade keeps a stored disabled state and tolerates null params ---");
        var path = Path.Combine(Path.GetTempPath(), $"nya_memv2_cfg_{Guid.NewGuid():N}.db");
        try
        {
            using (var db = BrokerCore.Data.BrokerDb.UseSqlite($"Data Source={path};Pooling=False"))
            {
                db.EnsureTable<NyaConfigEntry>();
                db.Insert(new NyaConfigEntry { ConfigKey = "nya:chat", ConfigJson = "{\"Enabled\":false,\"ShortTermMessageLimit\":30}" });
                var store = new NyaChatConfigStore(new NyaChatConfig { Enabled = true }, db, NullLogger<NyaChatConfigStore>.Instance);
                AssertTrue("stored-disabled-kept", store.Current.Enabled == false);
                AssertEqual("stored-limit-kept", 30, store.Current.ShortTermMessageLimit);
            }
            var entry = new NyaLlmProfileEntry { ProfileId = "legacy", Provider = "openai_chat", BaseUrl = "http://localhost:1234/v1/chat/completions", Model = "m",
                ParamsJson = "{\"temperature\":null,\"presence_penalty\":null,\"model_overrides\":{\"top_k\":null,\"min_p\":0}}" };
            var profile = entry.ToProfile();
            AssertTrue("null-params-tolerated", profile.Temperature > 0 && profile.ModelOverrides is { } o && o.ContainsKey("min_p") && !o.ContainsKey("top_k"));
        }
        finally
        {
            foreach (var p in new[] { path, path + "-shm", path + "-wal" })
                try { if (File.Exists(p)) File.Delete(p); } catch { }
        }
    }

    private static NyaToolContext Ctx(string userId, string args)
        => new() { ToolName = "search_history", UserId = userId, ChannelType = "line", ArgumentsJson = args };

    private sealed class Fixture : IDisposable
    {
        private readonly string _path = Path.Combine(Path.GetTempPath(), $"nya_memv2_{Guid.NewGuid():N}.db");
        public readonly ServiceProvider Services;
        public readonly CapturingProvider Llm = new();
        public string UserId { get; } = "nya_memv2_user";
        public NyaMemoryService Memory => Services.GetRequiredService<NyaMemoryService>();

        public Fixture()
        {
            var services = new ServiceCollection();
            services.AddSingleton(typeof(ILogger<>), typeof(NullLogger<>));
            services.AddSingleton<Microsoft.Extensions.Configuration.IConfiguration>(
                new Microsoft.Extensions.Configuration.ConfigurationBuilder().Build());
            services.AddSingleton<INyaLlmProvider>(Llm);
            services.AddNyaChat(new NyaChatConfig
            {
                Enabled = true,
                DbPath = $"{_path};Pooling=False",
                LlmProfiles = new() { ["fake_chat"] = new NyaLlmProfile { Provider = "fake", Model = "m", MaxContextTokens = 32000 } },
                TaskRouting = new()
                {
                    ["chat"] = "fake_chat",
                    ["fact_extraction"] = "fake_chat",
                    ["summarization"] = "fake_chat"
                }
            });
            Services = services.BuildServiceProvider();
        }

        public Broker.NyaChat.Abstractions.NyaChatResult Chat(string message, string? conversationId = null)
            => Services.GetRequiredService<INyaChatOrchestrator>().ChatAsync(new NyaChatRequest
            {
                ChannelType = "line", ChannelUserId = UserId, Message = message, ConversationId = conversationId
            }, CancellationToken.None).GetAwaiter().GetResult();

        public void Dispose()
        {
            Services.Dispose();
            foreach (var p in new[] { _path, _path + "-shm", _path + "-wal" })
                try { if (File.Exists(p)) File.Delete(p); } catch { }
        }
    }

    private sealed class CapturingProvider : INyaLlmProvider
    {
        public string Key => "fake";
        public bool SupportsTools => true;
        public int CallCount;
        public List<NyaLlmMessage> LastMessages = new();
        public Task<NyaLlmResponse?> SendAsync(NyaLlmProviderRequest request, CancellationToken ct)
        {
            Interlocked.Increment(ref CallCount);
            LastMessages = request.Request.Messages.ToList();
            return Task.FromResult<NyaLlmResponse?>(new NyaLlmResponse { Content = "好的" });
        }
    }

    private static void AssertEqual<T>(string name, T expected, T actual)
    {
        if (Equals(expected, actual)) { Console.WriteLine($"  [PASS] {name}"); _passed++; }
        else { Console.Error.WriteLine($"  [FAIL] {name}: expected '{expected}', got '{actual}'"); _failed++; }
    }

    private static void AssertTrue(string name, bool cond)
    {
        if (cond) { Console.WriteLine($"  [PASS] {name}"); _passed++; }
        else { Console.Error.WriteLine($"  [FAIL] {name}: expected true"); _failed++; }
    }
